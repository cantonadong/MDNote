class I18nState {
  systemLocale = $state<Locale>(detectSystemLocale());
  // "system" until Settings loads and says otherwise — see appState.init().
  override = $state<LanguageSetting>("system");

  get locale(): Locale {
    return this.override === "system" ? this.systemLocale : this.override;
  }

  t = (key: string, vars?: Record<string, string>): string => {
    let text = dict[this.locale][key] ?? dict.zh[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        text = text.replaceAll(`{${k}}`, v);
      }
    }
    return text;
  };

  setLanguage(value: LanguageSetting) {
    this.override = value;
  }
}

export const i18n = new I18nState();
