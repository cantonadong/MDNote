// Minimal hand-rolled i18n: a flat key->string dictionary per locale and a
// reactive t() lookup, rather than pulling in a full i18n library for what's
// currently two languages and a few hundred short UI strings.
export type Locale = "zh" | "en";
export type LanguageSetting = Locale | "system";

function detectSystemLocale(): Locale {
  const lang = (typeof navigator !== "undefined" && navigator.language) || "zh";
  return lang.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function formatSyncTime(iso: string, locale: Locale): string {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  const hh = String(d.getHours()).padStart(2, "0");
  const mm = String(d.getMinutes()).padStart(2, "0");
  if (locale === "zh") {
    return `${d.getMonth() + 1}月${d.getDate()}日 ${hh}:${mm}`;
  }
  const month = d.toLocaleString("en-US", { month: "short" });
  return `${month} ${d.getDate()}, ${hh}:${mm}`;
}

